// Generates src/bidi-class-data.ts from scripts/data/DerivedBidiClass-17.0.0.txt
// (https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedBidiClass.txt,
// sha256 4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4).
// Run: npm run gen:bidi-class
import { readFileSync, writeFileSync } from 'node:fs';

const INPUT = new URL('./data/DerivedBidiClass-17.0.0.txt', import.meta.url);
const OUTPUT = new URL('../src/bidi-class-data.ts', import.meta.url);
// Index i is encoded as the letter 'A' + i; must match `BidiClass` in src/bidi.ts.
const CLASSES = ['L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B', 'S', 'WS', 'ON',
  'LRE', 'LRO', 'RLE', 'RLO', 'PDF', 'LRI', 'RLI', 'FSI', 'PDI'];
const LONG_NAMES = {
  Left_To_Right: 'L', Right_To_Left: 'R', Arabic_Letter: 'AL', European_Terminator: 'ET',
};

const table = new Uint8Array(0x110000);
const fill = (from, to, cls) => {
  const index = CLASSES.indexOf(cls);
  if (index < 0) throw new Error(`unknown Bidi_Class ${cls}`);
  table.fill(index, parseInt(from, 16), parseInt(to ?? from, 16) + 1);
};
// `@missing` defaults first, in file order (later ones are more specific), then the data lines.
const lines = readFileSync(INPUT, 'utf8').split('\n');
for (const line of lines) {
  const m = /^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)/.exec(line);
  if (!m) continue;
  if (!LONG_NAMES[m[3]]) throw new Error(`unknown @missing class ${m[3]}`);
  fill(m[1], m[2], LONG_NAMES[m[3]]);
}
for (const line of lines) {
  const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/.exec(line);
  if (m) fill(m[1], m[2], m[3]);
}

// Each run's start, as the delta from the previous start in base 26: leading digits
// a-z, the last digit A-Z. Its class goes in a separate string, one letter per run:
// two homogeneous streams gzip ~15% smaller than interleaved runs.
let deltas = '';
let classes = '';
let previous = 0;
for (let cp = 0; cp < table.length; cp++) {
  if (cp > 0 && table[cp] === table[cp - 1]) continue;
  const digits = [];
  for (let d = cp - previous; digits.length === 0 || d > 0; d = Math.floor(d / 26)) digits.unshift(d % 26);
  deltas += digits.map((d, i) => String.fromCharCode((i === digits.length - 1 ? 65 : 97) + d)).join('');
  classes += String.fromCharCode(65 + table[cp]);
  previous = cp;
}

writeFileSync(OUTPUT, `// Generated by scripts/gen-bidi-class.mjs from Unicode 17.0.0 DerivedBidiClass.txt. Do not edit.
/** Bidi_Class runs over all code points: each start's delta from the previous one, base 26 (digits a-z, last digit A-Z). */
export const BIDI_RUN_STARTS =
  '${deltas}';
/** Each run's class, as \`'A' + index\` into the class list in scripts/gen-bidi-class.mjs. */
export const BIDI_RUN_CLASSES =
  '${classes}';
`);
console.log(`${classes.length} runs written to src/bidi-class-data.ts`);
